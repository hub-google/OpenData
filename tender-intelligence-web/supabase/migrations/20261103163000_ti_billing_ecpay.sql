
-- Taiwan tender intelligence: billing foundation, separated from other apps in the shared project.
create table if not exists public.ti_billing_plans (
  code text primary key check (code in ('personal','professional','team')),
  label text not null,
  amount_twd integer not null check(amount_twd > 0),
  is_available boolean not null default true
);
insert into public.ti_billing_plans(code,label,amount_twd) values
 ('personal','個人版',590),('professional','專業版',1590),('team','團隊版',3990)
on conflict (code) do nothing;

create table if not exists public.ti_billing_orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  merchant_trade_no varchar(20) not null unique,
  plan_code text not null references public.ti_billing_plans(code),
  amount_twd integer not null check(amount_twd>0),
  payment_kind text not null check(payment_kind in ('recurring','one_time')),
  status text not null default 'pending' check(status in ('pending','paid','failed','cancelled')),
  provider text not null default 'ecpay' check(provider='ecpay'),
  created_at timestamptz not null default now(),
  paid_at timestamptz,
  cancelled_at timestamptz
);
create index if not exists ti_billing_orders_user_created_idx on public.ti_billing_orders(user_id,created_at desc);

create table if not exists public.ti_billing_payments (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.ti_billing_orders(id) on delete cascade,
  provider_trade_no varchar(64) not null unique,
  amount_twd integer not null check(amount_twd>0),
  method text,
  paid_at timestamptz not null,
  processed_at timestamptz not null default now()
);
create index if not exists ti_billing_payments_order_idx on public.ti_billing_payments(order_id,paid_at desc);

create table if not exists public.ti_billing_subscriptions (
  user_id uuid primary key references auth.users(id) on delete cascade,
  plan_code text not null references public.ti_billing_plans(code),
  source_order_id uuid not null references public.ti_billing_orders(id),
  current_period_end timestamptz not null,
  auto_renew boolean not null default false,
  status text not null default 'active' check(status in ('active','cancelled','past_due')),
  updated_at timestamptz not null default now()
);

alter table public.ti_billing_plans enable row level security;
alter table public.ti_billing_orders enable row level security;
alter table public.ti_billing_payments enable row level security;
alter table public.ti_billing_subscriptions enable row level security;
revoke all on public.ti_billing_plans,public.ti_billing_orders,public.ti_billing_payments,public.ti_billing_subscriptions from anon,authenticated;
grant select on public.ti_billing_plans to anon,authenticated;
