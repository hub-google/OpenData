);

-- Only the service role can invoke this atomic, idempotent payment recorder after CheckMac verification.
create or replace function public.ti_record_ecpay_payment(
 p_merchant_trade_no text,p_provider_trade_no text,p_amount_twd integer,
 p_paid_at timestamptz,p_method text
) returns boolean language plpgsql security definer set search_path = '' as $$
declare
 v_order public.ti_billing_orders%rowtype;
 v_new_id bigint;
begin
 select * into v_order from public.ti_billing_orders
  where merchant_trade_no=p_merchant_trade_no for update;
 if not found or v_order.amount_twd<>p_amount_twd or p_amount_twd<=0 or
    v_order.status in ('cancelled','failed') or
    nullif(trim(p_provider_trade_no),'') is null then
   return false;
 end if;
 insert into public.ti_billing_payments(order_id,provider_trade_no,amount_twd,method,paid_at)
 values (v_order.id,p_provider_trade_no,p_amount_twd,left(p_method,50),coalesce(p_paid_at,now()))
 on conflict (provider_trade_no) do nothing returning id into v_new_id;
 if v_new_id is null then
   return true; -- Provider redelivery; do not extend access twice.
 end if;
 update public.ti_billing_orders set status='paid',paid_at=coalesce(p_paid_at,now()) where id=v_order.id;
 insert into public.ti_billing_subscriptions(user_id,plan_code,source_order_id,current_period_end,auto_renew,status)
 values (v_order.user_id,v_order.plan_code,v_order.id,now()+interval '1 month',v_order.payment_kind='recurring','active')
 on conflict(user_id) do update
 set plan_code=excluded.plan_code,
     source_order_id=excluded.source_order_id,
     current_period_end=greatest(public.ti_billing_subscriptions.current_period_end,now())+interval '1 month',
     auto_renew=case
       when public.ti_billing_subscriptions.source_order_id=excluded.source_order_id
        and public.ti_billing_subscriptions.status='cancelled'
       then false
       else excluded.auto_renew
     end,
     status=case
       when public.ti_billing_subscriptions.source_order_id=excluded.source_order_id
        and public.ti_billing_subscriptions.status='cancelled'
       then 'cancelled'
       else 'active'
     end,
     updated_at=now();
 return true;
end;
$$;
revoke all on function public.ti_record_ecpay_payment(text,text,integer,timestamptz,text) from public,anon,authenticated;
grant execute on function public.ti_record_ecpay_payment(text,text,integer,timestamptz,text) to service_role;
