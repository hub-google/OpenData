drop policy if exists ti_billing_plans_read on public.ti_billing_plans;
create policy ti_billing_plans_read on public.ti_billing_plans for select to anon,authenticated using (true);
drop policy if exists ti_billing_orders_own on public.ti_billing_orders;
create policy ti_billing_orders_own on public.ti_billing_orders for select to authenticated using ((select auth.uid())=user_id);
drop policy if exists ti_billing_subscriptions_own on public.ti_billing_subscriptions;
create policy ti_billing_subscriptions_own on public.ti_billing_subscriptions for select to authenticated using ((select auth.uid())=user_id);
